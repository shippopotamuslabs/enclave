"""Generate third_party/classifier_core/src/lib.rs from trained weights."""

from __future__ import annotations

from pathlib import Path


def write_linear_rust(
    path: Path,
    weights: list[float],
    bias: float,
    test_accuracy: float,
    sources_summary: str,
    recommended_threshold: float,
) -> None:
    if len(weights) != 384:
        raise ValueError(f"Expected 384 weights, got {len(weights)}")

    weight_lines = "\n".join(f"    {w:.6f}f32," for w in weights)
    rust = f"""// Auto-generated by scripts/search_intent_train. DO NOT EDIT.
// {sources_summary}
// Hold-out test accuracy: {test_accuracy:.4f}
// Golden-set recommended threshold: {recommended_threshold:.2f}
uniffi::setup_scaffolding!();

pub const EMBEDDING_DIM: usize = 384;
pub const RECOMMENDED_THRESHOLD: f32 = {recommended_threshold:.4f}f32;

pub const WEIGHTS: [f32; 384] = [
{weight_lines}
];

pub const BIAS: f32 = {bias:.6f}f32;

#[uniffi::export]
pub fn get_search_intent_probability(embedding: Vec<f32>) -> f32 {{
    linear_probability(embedding)
}}

fn linear_probability(embedding: Vec<f32>) -> f32 {{
    if embedding.len() != EMBEDDING_DIM {{
        return 0.0;
    }}
    let mut score = BIAS;
    for i in 0..EMBEDDING_DIM {{
        score += embedding[i] * WEIGHTS[i];
    }}
    sigmoid(score)
}}

#[uniffi::export]
pub fn classify_search_intent(embedding: Vec<f32>, threshold: f32) -> bool {{
    get_search_intent_probability(embedding) >= threshold
}}

fn sigmoid(x: f32) -> f32 {{
    1.0 / (1.0 + (-x).exp())
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn test_zero_embedding_returns_valid_probability() {{
        let prob = get_search_intent_probability(vec![0.0; EMBEDDING_DIM]);
        assert!((0.0..=1.0).contains(&prob));
    }}

    #[test]
    fn test_invalid_length_returns_zero() {{
        assert_eq!(get_search_intent_probability(vec![0.0; 100]), 0.0);
    }}
}}
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(rust, encoding="utf-8")


def write_mlp_rust(
    path: Path,
    w1: list[list[float]],
    b1: list[float],
    w2: list[float],
    b2: float,
    test_accuracy: float,
    sources_summary: str,
    recommended_threshold: float,
    hidden_dim: int,
) -> None:
    in_dim = len(w1[0])
    if in_dim != 384 or len(w1) != hidden_dim or len(b1) != hidden_dim or len(w2) != hidden_dim:
        raise ValueError("Unexpected MLP shape")

    def fmt_row(row: list[float]) -> str:
        return ", ".join(f"{v:.6f}f32" for v in row)

    w1_rows = ",\n".join(f"    [{fmt_row(row)}]" for row in w1)
    b1_vals = ", ".join(f"{v:.6f}f32" for v in b1)
    w2_vals = ", ".join(f"{v:.6f}f32" for v in w2)

    rust = f"""// Auto-generated by scripts/search_intent_train. DO NOT EDIT.
// {sources_summary}
// Head: MLP ({in_dim} -> {hidden_dim} -> 1), ReLU hidden
// Hold-out test accuracy: {test_accuracy:.4f}
// Golden-set recommended threshold: {recommended_threshold:.2f}
uniffi::setup_scaffolding!();

pub const EMBEDDING_DIM: usize = 384;
pub const HIDDEN_DIM: usize = {hidden_dim};
pub const RECOMMENDED_THRESHOLD: f32 = {recommended_threshold:.4f}f32;

pub const W1: [[f32; EMBEDDING_DIM]; HIDDEN_DIM] = [
{w1_rows}
];

pub const B1: [f32; HIDDEN_DIM] = [{b1_vals}];

pub const W2: [f32; HIDDEN_DIM] = [{w2_vals}];

pub const B2: f32 = {b2:.6f}f32;

#[uniffi::export]
pub fn get_search_intent_probability(embedding: Vec<f32>) -> f32 {{
    mlp_probability(embedding)
}}

fn mlp_probability(embedding: Vec<f32>) -> f32 {{
    if embedding.len() != EMBEDDING_DIM {{
        return 0.0;
    }}
    let mut hidden = [0.0f32; HIDDEN_DIM];
    for j in 0..HIDDEN_DIM {{
        let mut sum = B1[j];
        for i in 0..EMBEDDING_DIM {{
            sum += embedding[i] * W1[j][i];
        }}
        hidden[j] = sum.max(0.0);
    }}
    let mut logit = B2;
    for j in 0..HIDDEN_DIM {{
        logit += hidden[j] * W2[j];
    }}
    sigmoid(logit)
}}

#[uniffi::export]
pub fn classify_search_intent(embedding: Vec<f32>, threshold: f32) -> bool {{
    get_search_intent_probability(embedding) >= threshold
}}

fn sigmoid(x: f32) -> f32 {{
    1.0 / (1.0 + (-x).exp())
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn test_zero_embedding_returns_valid_probability() {{
        let prob = get_search_intent_probability(vec![0.0; EMBEDDING_DIM]);
        assert!((0.0..=1.0).contains(&prob));
    }}

    #[test]
    fn test_invalid_length_returns_zero() {{
        assert_eq!(get_search_intent_probability(vec![0.0; 100]), 0.0);
    }}
}}
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(rust, encoding="utf-8")
